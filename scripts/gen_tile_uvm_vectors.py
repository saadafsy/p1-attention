#!/usr/bin/env python3
"""Golden vectors for the matmul_tile UVM environment (tb/uvm), and the
post-simulation checker for its constrained-random test.

Two modes, one mirror. The mirror is the tile contract of docs/uarch.md 8.1
applied to all 16 accumulators with 24-bit wrap, the same semantics
tb/matmul_tile/test_matmul_tile.py's TileMirror uses and the same exact
integer products model/attn.py's SACC loop uses. It is the ONLY reference
the UVM environment ever compares against; there is deliberately no
SystemVerilog model of the MAC (target-scores change 1, "do not write a
second reference model").

  --emit  seed  out.txt   Constrained-random stimulus (weighted toward the
                          Q1.6 edges) plus the expected acc_flat after every
                          edge. tb/uvm's replay sequence drives the stimulus
                          columns and its scoreboard compares acc_flat with
                          the expected columns on every cycle.
  --check trace.txt       Check a trace the UVM monitor wrote during the
                          SV-constrained-random test (same columns, acc
                          columns are OBSERVED): recompute expected from the
                          stimulus and diff. Exit 1 on any mismatch.

File format, one line per clock edge, whitespace separated, '#' comments:
  rst en clr q0 q1 q2 q3 k0 k1 k2 k3 acc(0,0) acc(0,1) ... acc(3,3)
q/k are signed int8 codes, acc are signed 24-bit values AFTER the edge
(row-major, element (i,j) at position 4*i+j).
"""
import argparse
import random
import sys

ACC_MOD = 1 << 24
D = 16


def wrap24(x):
    return ((x + (1 << 23)) % ACC_MOD) - (1 << 23)


def step(acc, rst, en, clr, q, k):
    if rst:
        return [[0] * 4 for _ in range(4)]
    new = [[0] * 4 for _ in range(4)]
    for i in range(4):
        for j in range(4):
            base = 0 if clr else acc[i][j]
            new[i][j] = wrap24(base + q[i] * k[j]) if en else base
    return new


EDGES = [-128, -64, -1, 0, 1, 63, 127]


def rand_act(rng):
    # 40% exact edge values, 60% uniform: biases the corners UVM coverage
    # wants (sign combinations, |x| = 128 products) without excluding any code.
    return rng.choice(EDGES) if rng.random() < 0.4 else rng.randint(-128, 127)


def emit(seed, path, dots=200):
    rng = random.Random(seed)
    acc = [[0] * 4 for _ in range(4)]
    lines = ["# rst en clr q0 q1 q2 q3 k0 k1 k2 k3 acc00 acc01 acc02 acc03 acc10 ... acc33",
             f"# generated by scripts/gen_tile_uvm_vectors.py --emit {seed}"]
    def push(rst, en, clr, q, k):
        nonlocal acc
        acc = step(acc, rst, en, clr, q, k)
        flat = [acc[i][j] for i in range(4) for j in range(4)]
        lines.append(" ".join(str(x) for x in [rst, en, clr] + q + k + flat))
    q0 = [0] * 4
    push(1, 0, 0, q0, q0)
    push(1, 0, 0, q0, q0)
    push(0, 0, 0, q0, q0)
    for _ in range(dots):
        mode = rng.random()
        if mode < 0.05:
            push(1, 0, 0, [rand_act(rng) for _ in range(4)], [rand_act(rng) for _ in range(4)])
            continue
        # one full D=16 dot product, clr on d=0, optional hold bubbles inside
        for d in range(D):
            q = [rand_act(rng) for _ in range(4)]
            k = [rand_act(rng) for _ in range(4)]
            if d > 0 and rng.random() < 0.08:
                push(0, 0, 0, q, k)              # hold: en=0, garbage operands
            push(0, 1, 1 if d == 0 else 0, q, k)
        if rng.random() < 0.15:
            push(0, 0, 1, [0] * 4, [0] * 4)      # clr without en: clear
        if rng.random() < 0.3:
            for _ in range(rng.randint(1, 3)):
                push(0, 0, 0, [rand_act(rng) for _ in range(4)], [rand_act(rng) for _ in range(4)])
    with open(path, "w", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {path}: {len(lines) - 2} cycles, {dots} dot products, seed {seed}")


def check(path):
    acc = [[0] * 4 for _ in range(4)]
    n = bad = 0
    for lineno, raw in enumerate(open(path), 1):
        s = raw.strip()
        if not s or s.startswith("#"):
            continue
        v = [int(x) for x in s.split()]
        if len(v) != 3 + 8 + 16:
            print(f"{path}:{lineno}: expected 27 columns, got {len(v)}")
            return 1
        rst, en, clr = v[0], v[1], v[2]
        q, k, got = v[3:7], v[7:11], v[11:27]
        acc = step(acc, rst, en, clr, q, k)
        exp = [acc[i][j] for i in range(4) for j in range(4)]
        n += 1
        if got != exp:
            bad += 1
            if bad <= 10:
                print(f"{path}:{lineno}: MISMATCH rst={rst} en={en} clr={clr} q={q} k={k}\n   dut={got}\n   ref={exp}")
    print(f"checked {n} cycles: {'PASS' if bad == 0 else f'FAIL ({bad} mismatching cycles)'}")
    return 0 if bad == 0 and n > 0 else 1


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--emit", nargs=2, metavar=("SEED", "OUT"))
    ap.add_argument("--dots", type=int, default=200)
    ap.add_argument("--check", metavar="TRACE")
    a = ap.parse_args()
    if a.emit:
        emit(int(a.emit[0]), a.emit[1], a.dots)
        return 0
    if a.check:
        return check(a.check)
    ap.print_help()
    return 2


if __name__ == "__main__":
    sys.exit(main())
